"""Regenerate every ``_sync/`` directory from its ``_async/`` sibling with unasync.

    python tools/generate_sync.py

The async code is the source (roadmap 0.2, p4); the generated sync copy is
committed, so installing the library needs no build step.
``tests/test_generated_sync.py`` regenerates into a temporary directory and
fails on any difference, in content or in the set of files.

Every source file starts with a one-line comment, which the
generator replaces with the do-not-edit marker.  That keeps line numbers equal
in both copies, so a traceback through ``_sync/`` names the same line as the
source it came from.
"""

from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

import unasync

REPO = Path(__file__).resolve().parent.parent

# The directories holding an ``_async/`` to generate a ``_sync/`` next to.
ROOTS = [REPO / "src" / "calendaring", REPO / "tests"]

# The Go convention for generated code (golang.org/s/generatedcode), in
# Python comment syntax, so tools that skip generated files recognise these.
MARKER = "# Code generated by tools/generate_sync.py from _async/; DO NOT EDIT.\n"

# Names that must not follow unasync's ``AsyncX`` -> ``SyncX`` rename.  The
# I/O classes follow httpx: the sync class is unprefixed (API_DESIGN.md §1.1).
# Items keep the default rename (``AsyncTask`` -> ``SyncTask``).
REPLACEMENTS = {
    "_async": "_sync",
    "AsyncWorkspace": "Workspace",
    "AsyncBackend": "Backend",
    "AsyncCollection": "Collection",
    "AsyncMemoryBackend": "MemoryBackend",
    "AsyncMemoryCollection": "MemoryCollection",
    # the per-mode layer (calendaring/_concurrency.py)
    "agather": "gather",
}

RULE = unasync.Rule("/_async/", "/_sync/", additional_replacements=REPLACEMENTS)


def generate(root: Path, out_root: Path | None = None) -> set[Path]:
    """Write ``out_root/_sync`` from ``root/_async/``, recursively; delete orphans.

    Returns the generated paths, relative to ``_sync/``.  ``out_root``
    defaults to ``root``; the freshness test points it elsewhere.
    """
    dst = (out_root or root) / "_sync"
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "_async"
        shutil.copytree(root / "_async", work, ignore=shutil.ignore_patterns("__pycache__"))
        unasync.unasync_files([str(p) for p in sorted(work.rglob("*.py"))], [RULE])
        produced = Path(tmp) / "_sync"
        expected = {p.relative_to(produced) for p in produced.rglob("*.py")}
        for rel in sorted(expected):
            lines = (produced / rel).read_text().splitlines(keepends=True)
            if not lines:
                raise ValueError(f"{root.name}/_async/{rel} is empty: give it a one-line comment")
            if not lines[0].startswith("#"):
                raise ValueError(f"{root.name}/_async/{rel} must start with a one-line comment")
            lines[0] = MARKER
            (dst / rel).parent.mkdir(parents=True, exist_ok=True)
            (dst / rel).write_text("".join(lines))
    for old in list(dst.rglob("*.py")) if dst.exists() else []:
        if old.relative_to(dst) not in expected:
            old.unlink()
    return expected


if __name__ == "__main__":
    for root in ROOTS:
        for rel in sorted(generate(root)):
            print(f"{root.relative_to(REPO)}/_sync/{rel}")
    sys.exit(0)
